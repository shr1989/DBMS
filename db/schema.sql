-- Hotel Management System — schema
-- Table definitions are taken unchanged from the project report (section 7.1).
-- IF NOT EXISTS only makes this script safe to re-run; it never alters or drops anything.

CREATE TABLE IF NOT EXISTS GUEST (
    GUEST_ID INT PRIMARY KEY,
    GUEST_NAME VARCHAR(50) NOT NULL,
    PHONE VARCHAR(15) UNIQUE NOT NULL,
    EMAIL VARCHAR(100) UNIQUE,
    ADDRESS VARCHAR(100),
    CITY VARCHAR(50),
    ID_PROOF_NO VARCHAR(30) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS ROOM_TYPE (
    TYPE_ID INT PRIMARY KEY,
    TYPE_NAME VARCHAR(30) UNIQUE NOT NULL,
    BASE_PRICE NUMERIC(10,2) NOT NULL CHECK (BASE_PRICE > 0),
    CAPACITY INT NOT NULL CHECK (CAPACITY > 0)
);

CREATE TABLE IF NOT EXISTS ROOM (
    ROOM_ID INT PRIMARY KEY,
    ROOM_NO INT UNIQUE NOT NULL,
    FLOOR_NO INT NOT NULL CHECK (FLOOR_NO > 0),
    ROOM_STATUS VARCHAR(20) DEFAULT 'Available'
        CHECK (ROOM_STATUS IN ('Available', 'Occupied', 'Maintenance')),
    TYPE_ID INT NOT NULL,
    FOREIGN KEY (TYPE_ID) REFERENCES ROOM_TYPE(TYPE_ID)
);

CREATE TABLE IF NOT EXISTS DEPARTMENT (
    DEPT_ID INT PRIMARY KEY,
    DEPT_NAME VARCHAR(50) UNIQUE NOT NULL,
    LOCATION VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS EMPLOYEE (
    EMP_ID INT PRIMARY KEY,
    EMP_NAME VARCHAR(50) NOT NULL,
    DESIGNATION VARCHAR(50),
    SALARY NUMERIC(10,2) CHECK (SALARY > 0),
    HIRE_DATE DATE NOT NULL,
    DEPT_ID INT NOT NULL,
    MANAGER_ID INT,
    FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT(DEPT_ID),
    FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEE(EMP_ID)
);

CREATE TABLE IF NOT EXISTS BOOKING (
    BOOKING_ID INT PRIMARY KEY,
    BOOKING_DATE DATE NOT NULL,
    CHECKIN_DATE DATE NOT NULL,
    CHECKOUT_DATE DATE NOT NULL,
    TOTAL_AMOUNT NUMERIC(10,2) CHECK (TOTAL_AMOUNT >= 0),
    BOOKING_STATUS VARCHAR(20) DEFAULT 'Confirmed'
        CHECK (BOOKING_STATUS IN ('Confirmed', 'Checked-In', 'Checked-Out', 'Cancelled')),
    GUEST_ID INT NOT NULL,
    ROOM_ID INT NOT NULL,
    FOREIGN KEY (GUEST_ID) REFERENCES GUEST(GUEST_ID),
    FOREIGN KEY (ROOM_ID) REFERENCES ROOM(ROOM_ID),
    CHECK (CHECKOUT_DATE > CHECKIN_DATE)
);

CREATE TABLE IF NOT EXISTS PAYMENT (
    PAYMENT_ID INT PRIMARY KEY,
    AMOUNT NUMERIC(10,2) NOT NULL CHECK (AMOUNT > 0),
    PAY_DATE DATE NOT NULL,
    PAY_MODE VARCHAR(20) CHECK (PAY_MODE IN ('Cash', 'Card', 'UPI', 'Net Banking')),
    BOOKING_ID INT NOT NULL,
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID)
);

CREATE TABLE IF NOT EXISTS SERVICE (
    SERVICE_ID INT PRIMARY KEY,
    SERVICE_NAME VARCHAR(50) UNIQUE NOT NULL,
    SERVICE_PRICE NUMERIC(10,2) NOT NULL CHECK (SERVICE_PRICE > 0)
);

CREATE TABLE IF NOT EXISTS SERVICE_REQUEST (
    REQUEST_ID INT PRIMARY KEY,
    QUANTITY INT NOT NULL CHECK (QUANTITY > 0),
    REQUEST_DATE DATE NOT NULL,
    BOOKING_ID INT NOT NULL,
    SERVICE_ID INT NOT NULL,
    EMP_ID INT NOT NULL,
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID),
    FOREIGN KEY (SERVICE_ID) REFERENCES SERVICE(SERVICE_ID),
    FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);
